// An application menu bar (File, Edit, View…). The bar is one tab stop with Left/Right between
// menus; menus, items and submenus look exactly like `DropdownMenu`'s, and items keep the arrow
// cursor as native menus do. Radix supplies the roles, roving focus and typeahead.
function Menubar({
  className,
  ...props
}: React.ComponentProps<typeof MenubarPrimitive.Root>) {
  return (
    <MenubarPrimitive.Root
      data-slot="menubar"
      className={cn("flex h-8 items-center gap-0.5", className)}
      {...props}
    />
  )
}

