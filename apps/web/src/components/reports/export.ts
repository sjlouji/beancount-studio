import type { Balance, TreeNode } from "@/lib/api/types";
import { precisionFor } from "@/lib/format";

/** A flat, unit-expanded table that both CSV and Markdown are generated from. */
export interface ExportTable {
  title: string;
  headers: string[];
  rows: string[][];
  /** Columns from this index onwards are numeric (right-aligned in Markdown). */
  numericFrom: number;
}

export interface ExportReport {
  title: string;
  subtitle?: string;
  tables: ExportTable[];
}

export interface ExportRow {
  lead: string[];
  /** One balance per entry of `valueHeaders`. */
  values: Balance[];
}

function hasValue(balance: Balance): boolean {
  return Object.values(balance).some((v) => v !== 0);
}

/** Fixed-point text for a balance cell; empty when the value rounds to zero. */
function numberCell(value: number | undefined, unit: string, precisions: Record<string, number>, invert: boolean): string {
  if (value === undefined || !Number.isFinite(value)) return "";
  const digits = precisionFor(unit, precisions);
  const shown = invert ? -value : value;
  if (Math.abs(shown) < 0.5 * 10 ** -digits) return "";
  return shown.toFixed(digits);
}

/**
 * Expand each balance column into one column per unit. Columns that are empty for every row
 * (a unit that never appears in that measure) are dropped so spreadsheets stay narrow.
 */
export function buildTable({
  title,
  leadHeaders,
  valueHeaders,
  rows,
  precisions,
  invert = false,
}: {
  title: string;
  leadHeaders: string[];
  valueHeaders: string[];
  rows: ExportRow[];
  precisions: Record<string, number>;
  invert?: boolean;
}): ExportTable {
  const units = Array.from(new Set(rows.flatMap((row) => row.values.flatMap((b) => Object.keys(b))))).sort();
  const columns: Array<{ header: string; valueIndex: number; unit: string }> = [];
  valueHeaders.forEach((header, valueIndex) => {
    for (const unit of units) {
      if (rows.some((row) => numberCell(row.values[valueIndex]?.[unit], unit, precisions, invert) !== "")) {
        columns.push({ header: `${header} (${unit})`, valueIndex, unit });
      }
    }
  });
  return {
    title,
    headers: [...leadHeaders, ...columns.map((c) => c.header)],
    rows: rows.map((row) => [...row.lead, ...columns.map((c) => numberCell(row.values[c.valueIndex]?.[c.unit], c.unit, precisions, invert))]),
    numericFrom: leadHeaders.length,
  };
}

/** Rows of a statement tree (depth-first) followed by optional summary rows. */
export function treeTable({
  title,
  root,
  precisions,
  invert = false,
  summary = [],
}: {
  title: string;
  root: TreeNode;
  precisions: Record<string, number>;
  invert?: boolean;
  summary?: Array<{ label: string; balance: Balance }>;
}): ExportTable {
  const rows: ExportRow[] = [];
  const walk = (node: TreeNode, depth: number) => {
    rows.push({ lead: [node.account, String(depth)], values: [node.balance, node.balanceChildren] });
    for (const child of node.children) {
      if (hasValue(child.balanceChildren) || child.hasTxns) walk(child, depth + 1);
    }
  };
  walk(root, 0);
  for (const item of summary) rows.push({ lead: [item.label, ""], values: [{}, item.balance] });
  return buildTable({ title, leadHeaders: ["Account", "Depth"], valueHeaders: ["Balance", "Total"], rows, precisions, invert });
}

function csvField(value: string): string {
  return /[",\n\r]/.test(value) ? `"${value.replace(/"/g, '""')}"` : value;
}

/** RFC 4180 CSV; with several tables each one is preceded by its title and separated by a blank line. */
export function toCsv(tables: ExportTable[]): string {
  const blocks = tables.map((table) => {
    const lines = [table.headers, ...table.rows].map((line) => line.map(csvField).join(","));
    return (tables.length > 1 ? [csvField(table.title), ...lines] : lines).join("\r\n");
  });
  return blocks.join("\r\n\r\n") + "\r\n";
}

function mdCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ");
}

export function toMarkdown(report: ExportReport): string {
  const out: string[] = [`# ${report.title}`];
  if (report.subtitle) out.push("", `_${report.subtitle}_`);
  for (const table of report.tables) {
    out.push("", `## ${table.title}`, "");
    out.push(`| ${table.headers.map(mdCell).join(" | ")} |`);
    out.push(`| ${table.headers.map((_, i) => (i >= table.numericFrom ? "---:" : "---")).join(" | ")} |`);
    for (const row of table.rows) out.push(`| ${row.map(mdCell).join(" | ")} |`);
  }
  out.push("", `_Generated by Beancount Studio on ${new Date().toISOString().slice(0, 10)}._`, "");
  return out.join("\n");
}

/** Trigger a browser download of text content. */
export function downloadText(filename: string, content: string, mime: string): void {
  const url = URL.createObjectURL(new Blob([content], { type: mime }));
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  URL.revokeObjectURL(url);
}
